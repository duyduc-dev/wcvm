/** Ranges real semver.validRange() rejects. */
const INVALID = ["latest", "1.2.3.4", "01.2.3", "^1.2.3 || foo", ">=a", "1.2.3-", "~1.2.3-01"];

describe("semver", () => {
  it.each(SATISFIES)("%j accepts exactly what real semver accepts", (text, accepted) => {
    const range = parseRange(text);
    expect(range).toBeDefined();
    expect(VERSIONS.filter((v) => satisfies(parseVersion(v)!, range!))).toEqual(accepted);
  });

  it.each(MAX)("maxSatisfying(%j) matches real semver", (text, expected) => {
    expect(maxSatisfying(VERSIONS, parseRange(text)!) ?? null).toBe(expected);
  });

  it.each(INVALID)("%j is not a valid range", (text) => {
    expect(parseRange(text)).toBeUndefined();
  });

  it("parses versions, allowing a leading v/= and build metadata, rejecting leading zeros", () => {
    expect(parseVersion("v1.2.3-beta.1+build.5")).toEqual({ major: 1, minor: 2, patch: 3, prerelease: ["beta", 1] });
    expect(parseVersion("=1.0.0")).toEqual({ major: 1, minor: 0, patch: 0, prerelease: [] });
    for (const bad of ["1.2", "01.2.3", "1.2.3-01", "1.2.3-", "latest", "1.2.3.4"]) expect(parseVersion(bad)).toBeUndefined();
  });

  it("orders versions the way semver does, prereleases included", () => {
    const sorted = ["1.0.0", "1.0.0-rc.1", "1.0.0-alpha", "1.0.0-alpha.beta", "1.0.0-beta.11", "1.0.0-beta.2", "1.0.0-alpha.1", "1.0.0-beta", "0.9.0"]
      .map((v) => parseVersion(v)!)
      .sort(compareVersions)
      .map(formatVersion);
    // semver.org's own precedence example.
    expect(sorted).toEqual(["0.9.0", "1.0.0-alpha", "1.0.0-alpha.1", "1.0.0-alpha.beta", "1.0.0-beta", "1.0.0-beta.2", "1.0.0-beta.11", "1.0.0-rc.1", "1.0.0"]);
  });

  it.each([
    ["7", "7.8.5", true],
    ["^7.1.0", "7.8.5", true],
    ["*", "1.2.3", true],
    [">=1.0.0", "1.2.3", true],
    ["~1.1.0", "1.1.2", false],
    [">=2.0.0 <2.2.0", "2.1.3", false],
    ["1.2.3", "1.2.3", false],
    ["^0.2.0", "0.2.5", true],
    ["0.2.x", "0.2.5", true],
    ["1 || 2", "2.0.1", true],
  ])("coversCaret(%j, ^%s) is %s - npm's rule for what `npm install x@<range>` saves", (range, version, expected) => {
    expect(coversCaret(parseRange(range)!, parseVersion(version)!)).toBe(expected);
  });
});
