#!/usr/bin/env node
// Vendors a pinned set of Node.js `lib/` modules VERBATIM into
// src/runtime/node/lib/, each wrapped as a builtin factory, and regenerates
// src/runtime/node/registry.ts.
//
//   node scripts/vendor-node-lib.mjs           # fetch missing files, regenerate
//   node scripts/vendor-node-lib.mjs --check   # verify vendored bodies are untouched
//
// The module list is src/runtime/node/manifest.json. The upstream body of each
// file is never edited: only a header and a function wrapper are added, and the
// sha256 of the upstream text is recorded in vendor.lock.json so --check can
// prove that (tests run it).

import { execFileSync } from "node:child_process";
import { createHash } from "node:crypto";
import { existsSync, mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..", "src", "runtime", "node");
const libDir = join(root, "lib");
const manifest = JSON.parse(readFileSync(join(root, "manifest.json"), "utf8"));
const lockPath = join(root, "vendor.lock.json");
const lock = existsSync(lockPath) ? JSON.parse(readFileSync(lockPath, "utf8")) : { files: {} };

const { version, modules } = manifest;
const PARAMS = {
  builtin: "exports, require, module, process, internalBinding, primordials",
  per_context: "exports, primordials, privateSymbols, perIsolateSymbols",
};

const sha256 = (text) => createHash("sha256").update(text).digest("hex");
const fileFor = (id) => join(libDir, `${id}.js`);
const sourceUrl = (path) => `https://raw.githubusercontent.com/nodejs/node/${version}/${path}`;

// `internal/deps/X` ids are third-party code Node vendors outside `lib/`
// (e.g. acorn, at `deps/X.js`); everything else is `lib/<id>.js`.
const repoPathFor = (id) => (id.startsWith("internal/deps/") ? `${id.slice("internal/".length)}.js` : `lib/${id}.js`);

// curl, not fetch: it honours the https_proxy the sandbox needs.
const download = (path) =>
  execFileSync("curl", ["-sS", "-f", "-m", "60", sourceUrl(path)], {
    encoding: "utf8",
    maxBuffer: 64 * 1024 * 1024,
  });

const header = (id, kind) =>
  `// VENDORED VERBATIM from Node.js ${version} - ${repoPathFor(id)}\n` +
  `// Source: https://github.com/nodejs/node/blob/${version}/${repoPathFor(id)}\n` +
  `// Only this header and the function wrapper are added; do not edit the body.\n` +
  `// Regenerate with: node scripts/vendor-node-lib.mjs\n` +
  `export default function (${PARAMS[kind]}) {\n`;
const FOOTER = "\n}\n";

const wrap = (id, kind, body) => header(id, kind) + body + FOOTER;

const check = process.argv.includes("--check");
let failed = false;

for (const [id, kind = "builtin"] of Object.entries(modules)) {
  const file = fileFor(id);
  if (check) {
    const recorded = lock.files[id];
    if (!recorded || !existsSync(file)) {
      console.error(`missing: ${id}`);
      failed = true;
      continue;
    }
    const text = readFileSync(file, "utf8");
    const h = header(id, kind);
    const body = text.startsWith(h) && text.endsWith(FOOTER) ? text.slice(h.length, -FOOTER.length) : null;
    if (body === null || sha256(body) !== recorded) {
      console.error(`modified: ${id}`);
      failed = true;
    }
    continue;
  }

  if (existsSync(file) && lock.files[id]) continue;
  const body = download(repoPathFor(id));
  mkdirSync(dirname(file), { recursive: true });
  writeFileSync(file, wrap(id, kind, body));
  lock.files[id] = sha256(body);
  console.log(`vendored ${id}`);
}

if (check) process.exit(failed ? 1 : 0);

// Drop lock entries for ids removed from the manifest.
for (const id of Object.keys(lock.files)) if (!(id in modules)) delete lock.files[id];
writeFileSync(lockPath, JSON.stringify({ version, files: lock.files }, null, 2) + "\n");

const licensePath = join(root, "LICENSE");
if (!existsSync(licensePath)) writeFileSync(licensePath, download("LICENSE"));

const ids = Object.keys(modules).sort();
const importName = (id) => "f_" + id.replace(/[^A-Za-z0-9]/g, "_");
const registry =
  `// GENERATED by scripts/vendor-node-lib.mjs - do not edit.\n` +
  `import type { BuiltinFactory, PerContextFactory } from "./types";\n` +
  ids.map((id) => `import ${importName(id)} from "./lib/${id}.js";`).join("\n") +
  `\n\nexport const NODE_VERSION = ${JSON.stringify(version)};\n\n` +
  `export const builtinFactories: Record<string, BuiltinFactory> = {\n` +
  ids.filter((id) => (modules[id] ?? "builtin") === "builtin").map((id) => `  ${JSON.stringify(id)}: ${importName(id)},`).join("\n") +
  `\n};\n\nexport const perContextFactories: Record<string, PerContextFactory> = {\n` +
  ids.filter((id) => modules[id] === "per_context").map((id) => `  ${JSON.stringify(id)}: ${importName(id)},`).join("\n") +
  `\n};\n`;
writeFileSync(join(root, "registry.ts"), registry);
console.log(`registry: ${ids.length} modules (Node ${version})`);
